"""Quantitative tools exposed to the agent (L12: MCP Gateway in prod, direct call here).
A thin adapter around risk_tools.py, optimizer.py and governance_check.py: the functions stay
deterministic and return their EVIDENCE envelope (evidence_id, say, assumptions) —
the LLM never computes, it cites evidence. The investor profile and the run's reference date
(`as_of`) travel via ContextVars (one per run, see tools/context.py) because a Strands tool is stateless.

Point-in-time: every tool works on `RiskTools.at(as_of)`, where `as_of` is the run's reference date.
The model can ask for an EARLIER date but never a later one, and tools without an `as_of` argument
(governance_check, optimize) are cut at the run's date as well.
"""
from __future__ import annotations

from app.agents.governance import (
    governance_check as _gov,  # alias: the @tool below is named governance_check
)
from app.core.config import get_settings
from app.tools import optimizer as _optimizer
from app.tools.context import (  # noqa: F401  (current_profile / current_as_of are set by the orchestrator)
    current_as_of,
    current_profile,
    default_as_of,
    effective_as_of,
    persona_profile,
    run_as_of,
)
from app.tools.risk_tools import RiskTools, _eid
from strands import tool

_rt: RiskTools | None = None


def _tools() -> RiskTools:
    global _rt
    if _rt is None:
        s = get_settings()
        _rt = RiskTools(s.abs_path(s.curated_dir))
    return _rt


def _view(as_of: str | None = None) -> RiskTools:
    """Risk tools cut at the run's reference date (or at an earlier date asked for by the caller)."""
    return _tools().at(effective_as_of(as_of))


def _guard(fn, *args, **kwargs):
    """Input error (unknown ticker, empty window…) -> error dict so the model can react."""
    try:
        return fn(*args, **kwargs)
    except (KeyError, ValueError) as e:
        return {"error": str(e), "note": "Fix the arguments and call the tool again."}


@tool
def metrics(tickers: list[str], start: str | None = None, end: str | None = None,
            as_of: str | None = None) -> dict:
    """Total return, annualized volatility, worst drawdown, daily 95% VaR/CVaR
    per asset, in CAD, with an evidence record (evidence_id).
    Args:
        tickers: Assets from the universe (e.g. ["NVDA", "XBB.TO"]).
        start/end: Optional "YYYY-MM-DD" window.
        as_of: Optional earlier date; the run's reference date is the upper bound (nothing after it).
    """
    return _guard(_tools().metrics, tickers, start=start, end=end, as_of=effective_as_of(as_of))


@tool
def concentration(weights: dict[str, float], look_through: bool = True) -> dict:
    """Exposures by company, sector, asset class and currency, with a concentration
    index (HHI) and effective number of positions. Decomposes equity ETFs
    (SPY, QQQ, XIU…) via their published holdings (current composition).
    Args:
        weights: Portfolio weights.
        look_through: True (default) to decompose equity ETFs.
    """
    return _guard(lambda: _view().concentration(weights, look_through=look_through))


@tool
def correlation(tickers: list[str], start: str | None = None, end: str | None = None,
                as_of: str | None = None) -> dict:
    """Correlation matrix of daily returns in CAD between assets.
    Args:
        tickers: At least two assets from the universe.
        start/end: Optional window (comparing with 2022 is instructive).
        as_of: Optional earlier date; the run's reference date is the upper bound.
    """
    return _guard(_tools().correlation, tickers, start=start, end=end, as_of=effective_as_of(as_of))


@tool
def risk_contribution(weights: dict[str, float], start: str | None = None,
                      end: str | None = None, as_of: str | None = None) -> dict:
    """Share of total portfolio risk generated by each position, plus the
    diversification ratio (identifies what "weighs" on risk beyond its weight).
    Args:
        weights: Portfolio weights.
        start/end: Optional window.
        as_of: Optional earlier date; the run's reference date is the upper bound.
    """
    return _guard(_tools().risk_contribution, weights, start=start, end=end, as_of=effective_as_of(as_of))


@tool
def optimize(weights: dict[str, float], candidates: list[str] | None = None) -> dict:
    """Smallest change to a target portfolio that satisfies EVERY rule of the investor's profile
    (single position, sector, crypto, exclusions, short-horizon rules). No return forecast: the
    objective is the smallest adjustment plus a variance penalty. The result is verified with the
    governance tool before it is returned. If no allocation can satisfy the rules, status is
    "infeasible", with the conflicting rules and NO weights.
    Args:
        weights: Target portfolio (the investor's request or current holdings), e.g. {"XIU.TO": 0.5, "NVDA": 0.2}.
        candidates: Optional extra tickers allowed in the result (the tickers of `weights` are always candidates).
    """
    profile = persona_profile()
    if profile is None:
        return {"error": "No active profile for this run."}
    s = get_settings()
    cap = profile.get("capital")
    return _guard(_optimizer.optimize, _tools(), weights, profile, s.abs_path(s.rules_path),
                  candidates=candidates, as_of=run_as_of(), capital=cap,
                  data_dir=str(s.abs_path(s.curated_dir).parent))


@tool
def governance_check(weights: dict[str, float]) -> dict:
    """Checks an allocation against the investor's profile and the documented
    rules (rules.yaml): crisis-scenario loss limits, single position, sector,
    crypto, horizon, exclusions (ESG, controversies).
    Returns an overall PASS / WARN / BLOCK verdict with every check detailed.
    Args:
        weights: Weights to check (the current run's profile is used).
    """
    profile = persona_profile()
    if profile is None:
        return {"error": "No active profile for this run."}
    s = get_settings()
    result = _guard(lambda: _gov.check(weights, profile, s.abs_path(s.rules_path), _view(),
                                       str(s.abs_path(s.curated_dir).parent)))
    if "verdict" not in result:          # input error: nothing to cite
        return result
    total = sum(weights.values())
    inputs = {"weights": {k: round(v / total, 6) for k, v in sorted(weights.items())},
              "profile": profile.get("id"), "as_of": run_as_of(), "rules_version": result.get("rules_version")}
    flagged = [f"{c['id']} {c['status']}" for c in result["checks"] if c["status"] != "PASS"]
    say = (f"Governance verdict {result['verdict']} for this profile"
           + (f" ({', '.join(flagged)})." if flagged else ": every check passes."))
    # Evidence envelope (same shape as every tool) around the check, so the verdict can be cited.
    return {**result, "evidence_id": _eid("governance_check", inputs), "tool": "governance_check",
            "inputs": inputs, "output": result, "say": say, "currency": "CAD", "as_of": run_as_of(),
            "assumptions": ["Thresholds in rules.yaml are team assumptions, not regulatory standards.",
                            "Position and sector checks decompose equity ETFs with their CURRENT holdings.",
                            "Unverifiable exclusions are reported as UNVERIFIED, never as PASS."],
            "data_sources": ["backend/app/core/rules.yaml", "data/curated (prices, holdings, ESG screens)"]}


ALL_TOOLS = [metrics, concentration, correlation, risk_contribution, optimize,
             governance_check]
