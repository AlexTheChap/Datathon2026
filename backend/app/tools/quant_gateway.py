# ---------- dispatch ----------
_rt: RiskTools | None = None
_dir: Path | None = None


def curated_dir() -> Path:
    """AF_CURATED_S3 (S3 curated Parquet, synced to /tmp once per container) > AF_CURATED_DIR > repo CSVs."""
    global _dir
    if _dir is None:
        from app.tools.curated_store import curated_dir_from_env

        default = os.environ.get("AF_CURATED_DIR") or Path(__file__).resolve().parents[3] / "data" / "curated"
        _dir = curated_dir_from_env(default)
    return _dir


def tools() -> RiskTools:
    global _rt  # loaded once per Lambda container (file parsing is the slow part)
    if _rt is None:
        _rt = RiskTools(curated_dir())
    return _rt


def _macro(name: str, a: dict) -> dict:
    from app.tools import macro_tools

    if name == "macro_snapshot":
        return macro_tools.macro_snapshot(curated_dir(), a.get("as_of") or None)
    return macro_tools.fx_usdcad(curated_dir(), a.get("as_of") or None, a.get("start") or None)


_graph = None


def market_graph():
    """Neptune (AF_NEPTUNE_ENDPOINT) or the in-memory graph, created once per Lambda container."""
    global _graph
    if _graph is None:
        from app.market.graph import backend

        _graph = backend(curated_dir())
    return _graph


def _market(name: str, a: dict) -> dict:
    from app.market import graph

    return (graph.screen_tool if name == "screen" else graph.related_tool)(market_graph(), a)


def _weights(value: Any) -> dict[str, float]:
    """Accept {"NVDA": 0.2} or [{"ticker": "NVDA", "weight": 0.2}] (in case a client cannot send free keys)."""
    if isinstance(value, str):
        value = json.loads(value)
    if isinstance(value, list):
        value = {item["ticker"]: item["weight"] for item in value}
    if not isinstance(value, dict) or not value:
        raise ValueError("weights must be a non-empty object {ticker: weight}")
    return {str(k): float(v) for k, v in value.items()}


def _tickers(value: Any) -> list[str]:
    if isinstance(value, str):
        value = json.loads(value) if value.strip().startswith("[") else [value]
    return [str(t) for t in value]


def _opt(args: dict, *keys: str) -> dict:
    return {k: args[k] for k in keys if args.get(k) not in (None, "")}


HANDLERS: dict[str, Callable[[dict], dict]] = {
    "metrics": lambda a: tools().metrics(_tickers(a["tickers"]), **_opt(a, "start", "end", "as_of")),
    "correlation": lambda a: tools().correlation(_tickers(a["tickers"]), **_opt(a, "start", "end", "as_of")),
    "risk_contribution": lambda a: tools().risk_contribution(_weights(a["weights"]),
                                                             **_opt(a, "start", "end", "as_of")),
    "concentration": lambda a: tools().concentration(_weights(a["weights"]),
                                                     look_through=bool(a.get("look_through", True))),
    "macro_snapshot": lambda a: _macro("macro_snapshot", a),
    "fx_usdcad": lambda a: _macro("fx_usdcad", a),
    "screen": lambda a: _market("screen", a),
    "related": lambda a: _market("related", a),
}

assert set(HANDLERS) == {t["name"] for ts in TARGETS.values() for t in ts}, "schemas and handlers out of sync"


def call(tool_name: str, args: dict | None) -> dict:
    """Run one tool. `tool_name` may carry the Gateway prefix ("scenarios___stress")."""
    name = tool_name.split(DELIMITER, 1)[-1]
    if name not in HANDLERS:
        return {"error": f"Unknown tool: {tool_name}", "available": sorted(HANDLERS)}
    try:
        return json.loads(json.dumps(HANDLERS[name](args or {}), default=str))  # numpy/dates -> plain JSON
    except (KeyError, ValueError, TypeError) as e:
        return {"error": f"{type(e).__name__}: {e}", "note": "Fix the arguments and call the tool again."}


def handler(event: dict, context: Any = None) -> dict:
    """Lambda entry point for the Gateway target."""
    custom = getattr(getattr(context, "client_context", None), "custom", None) or {}
    tool_name = custom.get("bedrockAgentCoreToolName") or (event or {}).pop("__tool", "")
    return call(tool_name, event)
