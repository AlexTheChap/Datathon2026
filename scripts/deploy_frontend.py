"""Deploy box ① (the web app in frontend/) to S3 + CloudFront, with boto3 only.

    python scripts/deploy_frontend.py --dry-run                 # show what would be published / created, change nothing
    python scripts/deploy_frontend.py                           # create or update the site
    python scripts/deploy_frontend.py --api-url https://<id>.execute-api.us-east-1.amazonaws.com
                                                                # + route /v1/* to the API (box ②) on the same URL
    python scripts/deploy_frontend.py --delete                  # tear the site down

Credentials: --profile, otherwise the AWS_* variables, otherwise the repo's .env file (git-ignored).

What the script does (box ① and link L1 of docs/architecture.mmd):
1. S3 bucket "alphaforge-web-<account>-<region>": private (all public access blocked), encrypted. Uploads
   index.html, assets/ and a generated config.js; never the Streamlit dashboard (*.py) or the README.
   index.html and config.js are sent with "no-cache" so a new version shows at once; assets with 5 minutes.
2. CloudFront distribution (comment "alphaforge-web"): HTTPS only, the bucket read through an Origin Access
   Control (the bucket policy allows only this distribution), AWS managed security headers.
3. With --api-url: a second origin for the API Gateway URL and a /v1/* behaviour (no caching, every viewer
   header but Host forwarded, so the Cognito Bearer token reaches the API's JWT authorizer). The page then calls
   the API on its own origin: no CORS needed, and config.js keeps AF_API_BASE empty.
   Without --api-url the site still loads and signs in, but questions fail until the API exists.

config.js = the Cognito settings of frontend/config.js (written by scripts/setup_cognito.py), or none: the page
then runs in dev mode, which only works against a local API. The demo accounts' password is in it on purpose
(shared demo accounts, see setup_cognito.py). Re-running the script updates everything and invalidates the cache.
"""
from __future__ import annotations

import argparse
import json
import mimetypes
import re
import sys
import time
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
FRONTEND = ROOT / "frontend"
COMMENT = "alphaforge-web"
OAC_NAME = "alphaforge-web-oac"
TAGS = {"project": "alphaforge", "component": "frontend"}
NO_CACHE = "no-cache"
SHORT_CACHE = "public, max-age=300"
MANAGED = {  # AWS managed CloudFront policies, looked up by name (their ids are global constants)
    "cache_optimized": ("cache", "Managed-CachingOptimized"),
    "cache_disabled": ("cache", "Managed-CachingDisabled"),
    "all_viewer_except_host": ("origin_request", "Managed-AllViewerExceptHostHeader"),
    "security_headers": ("response_headers", "Managed-SecurityHeadersPolicy"),
}


# ---------- What is published (pure functions, unit-tested) ----------

def site_files(frontend: Path = FRONTEND) -> list[tuple[str, Path]]:
    """(S3 key, local file) for the static site: index.html + assets/. config.js is generated separately."""
    files = [("index.html", frontend / "index.html")]
    files += [(f"assets/{p.relative_to(frontend / 'assets').as_posix()}", p)
              for p in sorted((frontend / "assets").rglob("*")) if p.is_file() and "__pycache__" not in p.parts]
    return files


def content_type(key: str) -> str:
    known = {".js": "application/javascript", ".css": "text/css", ".html": "text/html", ".svg": "image/svg+xml"}
    suffix = Path(key).suffix
    base = known.get(suffix) or mimetypes.guess_type(key)[0] or "application/octet-stream"
    return f"{base}; charset=utf-8" if base.startswith("text/") or base.endswith("javascript") else base


def cache_control(key: str) -> str:
    return NO_CACHE if key in ("index.html", "config.js") else SHORT_CACHE


def config_js(cognito_config: str | None, api_base: str = "") -> str:
    """The page settings. `cognito_config` is the text of frontend/config.js (window.AF_CONFIG = {...};)."""
    head = "// Generated by scripts/deploy_frontend.py. Do not edit in S3: re-run the script.\n"
    body = cognito_config.strip() + "\n" if cognito_config else \
        "// No Cognito settings (run scripts/setup_cognito.py): the page runs in dev mode.\n"
    return head + body + f"window.AF_API_BASE = {json.dumps(api_base)};\n"


def api_origin(api_url: str) -> dict:
    """CloudFront custom origin for an API Gateway URL; a stage in the path (/prod) becomes the OriginPath."""
    u = urlparse(api_url if "://" in api_url else f"https://{api_url}")
    if u.scheme != "https" or not u.hostname:
        raise ValueError(f"--api-url must be an https URL, got {api_url!r}")
    return {"Id": "api", "DomainName": u.hostname, "OriginPath": u.path.rstrip("/"),
            "CustomHeaders": {"Quantity": 0},
            "CustomOriginConfig": {"HTTPPort": 80, "HTTPSPort": 443, "OriginProtocolPolicy": "https-only",
                                   "OriginSslProtocols": {"Quantity": 1, "Items": ["TLSv1.2"]},
                                   "OriginReadTimeout": 30, "OriginKeepaliveTimeout": 5},
            "ConnectionAttempts": 3, "ConnectionTimeout": 10, "OriginShield": {"Enabled": False}}


def distribution_config(bucket_domain: str, oac_id: str, policies: dict[str, str], caller_ref: str,
                        api_url: str | None = None) -> dict:
    s3_origin = {"Id": "site", "DomainName": bucket_domain, "OriginPath": "", "CustomHeaders": {"Quantity": 0},
                 "S3OriginConfig": {"OriginAccessIdentity": ""}, "OriginAccessControlId": oac_id,
                 "ConnectionAttempts": 3, "ConnectionTimeout": 10, "OriginShield": {"Enabled": False}}
    get_head = {"Quantity": 2, "Items": ["GET", "HEAD"], "CachedMethods": {"Quantity": 2, "Items": ["GET", "HEAD"]}}
    default = {"TargetOriginId": "site", "ViewerProtocolPolicy": "redirect-to-https", "Compress": True,
               "AllowedMethods": get_head, "CachePolicyId": policies["cache_optimized"],
               "ResponseHeadersPolicyId": policies["security_headers"],
               "TrustedSigners": {"Enabled": False, "Quantity": 0}, "TrustedKeyGroups": {"Enabled": False, "Quantity": 0},
               "SmoothStreaming": False, "FieldLevelEncryptionId": "",
               "LambdaFunctionAssociations": {"Quantity": 0}, "FunctionAssociations": {"Quantity": 0}}
    origins, behaviors = [s3_origin], []
    if api_url:
        origins.append(api_origin(api_url))
        all_methods = ["GET", "HEAD", "OPTIONS", "PUT", "POST", "PATCH", "DELETE"]
        behaviors.append({**default, "PathPattern": "/v1/*", "TargetOriginId": "api",
                          "ViewerProtocolPolicy": "https-only",
                          "AllowedMethods": {"Quantity": 7, "Items": all_methods,
                                             "CachedMethods": {"Quantity": 2, "Items": ["GET", "HEAD"]}},
                          "CachePolicyId": policies["cache_disabled"],
                          "OriginRequestPolicyId": policies["all_viewer_except_host"]})
    return {"CallerReference": caller_ref, "Comment": COMMENT, "Enabled": True, "DefaultRootObject": "index.html",
            "Origins": {"Quantity": len(origins), "Items": origins},
            "DefaultCacheBehavior": default,
            "CacheBehaviors": {"Quantity": len(behaviors), **({"Items": behaviors} if behaviors else {})},
            "PriceClass": "PriceClass_100", "HttpVersion": "http2and3", "IsIPV6Enabled": True,
            "ViewerCertificate": {"CloudFrontDefaultCertificate": True},
            "Restrictions": {"GeoRestriction": {"RestrictionType": "none", "Quantity": 0}},
            "CustomErrorResponses": {"Quantity": 0}, "Aliases": {"Quantity": 0}, "Logging": {
                "Enabled": False, "IncludeCookies": False, "Bucket": "", "Prefix": ""},
            "WebACLId": ""}


def bucket_policy(bucket: str, distribution_arn: str) -> dict:
    return {"Version": "2012-10-17", "Statement": [{
        "Sid": "CloudFrontReadsTheSite", "Effect": "Allow", "Principal": {"Service": "cloudfront.amazonaws.com"},
        "Action": "s3:GetObject", "Resource": f"arn:aws:s3:::{bucket}/*",
        "Condition": {"StringEquals": {"AWS:SourceArn": distribution_arn}}}]}


# ---------- AWS ----------

def managed_policy_ids(cf) -> dict[str, str]:
    listers = {"cache": lambda: cf.list_cache_policies(Type="managed")["CachePolicyList"]["Items"],
               "origin_request": lambda: cf.list_origin_request_policies(Type="managed")["OriginRequestPolicyList"]["Items"],
               "response_headers": lambda: cf.list_response_headers_policies(Type="managed")["ResponseHeadersPolicyList"]["Items"]}
    found: dict[str, str] = {}
    for key, (kind, name) in MANAGED.items():
        for item in listers[kind]():
            policy = item.get("CachePolicy") or item.get("OriginRequestPolicy") or item.get("ResponseHeadersPolicy")
            cfg = policy.get("CachePolicyConfig") or policy.get("OriginRequestPolicyConfig") or \
                policy.get("ResponseHeadersPolicyConfig")
            if cfg["Name"] == name:
                found[key] = policy["Id"]
        if key not in found:
            raise RuntimeError(f"CloudFront managed policy not found: {name}")
    return found


def find_distribution(cf) -> dict | None:
    for page in cf.get_paginator("list_distributions").paginate():
        for d in page.get("DistributionList", {}).get("Items", []):
            if d.get("Comment") == COMMENT:
                return d
    return None


def ensure_bucket(s3, bucket: str, region: str) -> None:
    try:
        s3.head_bucket(Bucket=bucket)
        print(f"• Existing bucket: s3://{bucket}")
    except s3.exceptions.ClientError:
        kwargs = {} if region == "us-east-1" else {"CreateBucketConfiguration": {"LocationConstraint": region}}
        s3.create_bucket(Bucket=bucket, **kwargs)
        s3.get_waiter("bucket_exists").wait(Bucket=bucket)
        print(f"• Bucket created: s3://{bucket}")
    s3.put_public_access_block(Bucket=bucket, PublicAccessBlockConfiguration={
        "BlockPublicAcls": True, "IgnorePublicAcls": True, "BlockPublicPolicy": True, "RestrictPublicBuckets": True})
    s3.put_bucket_encryption(Bucket=bucket, ServerSideEncryptionConfiguration={
        "Rules": [{"ApplyServerSideEncryptionByDefault": {"SSEAlgorithm": "AES256"}}]})
    s3.put_bucket_tagging(Bucket=bucket, Tagging={"TagSet": [{"Key": k, "Value": v} for k, v in TAGS.items()]})


def upload(s3, bucket: str, config_text: str) -> None:
    for key, path in site_files():
        s3.put_object(Bucket=bucket, Key=key, Body=path.read_bytes(), ContentType=content_type(key),
                      CacheControl=cache_control(key))
    s3.put_object(Bucket=bucket, Key="config.js", Body=config_text.encode(), ContentType=content_type("config.js"),
                  CacheControl=cache_control("config.js"))
    print(f"• Uploaded {len(site_files()) + 1} files (index.html, config.js, assets/)")


def ensure_oac(cf) -> str:
    for item in cf.list_origin_access_controls()["OriginAccessControlList"].get("Items", []):
        if item["Name"] == OAC_NAME:
            return item["Id"]
    return cf.create_origin_access_control(OriginAccessControlConfig={
        "Name": OAC_NAME, "Description": "AlphaForge web app: CloudFront reads the private bucket",
        "SigningProtocol": "sigv4", "SigningBehavior": "always", "OriginAccessControlOriginType": "s3"},
    )["OriginAccessControl"]["Id"]


def ensure_distribution(cf, bucket: str, region: str, api_url: str | None) -> dict:
    policies, oac = managed_policy_ids(cf), ensure_oac(cf)
    domain = f"{bucket}.s3.{region}.amazonaws.com"
    existing = find_distribution(cf)
    if existing:
        current = cf.get_distribution_config(Id=existing["Id"])
        cfg = distribution_config(domain, oac, policies, current["DistributionConfig"]["CallerReference"], api_url)
        dist = cf.update_distribution(Id=existing["Id"], IfMatch=current["ETag"], DistributionConfig=cfg)["Distribution"]
        print(f"• Distribution updated: {dist['Id']}")
    else:
        cfg = distribution_config(domain, oac, policies, f"alphaforge-web-{int(time.time())}", api_url)
        dist = cf.create_distribution_with_tags(DistributionConfigWithTags={
            "DistributionConfig": cfg, "Tags": {"Items": [{"Key": k, "Value": v} for k, v in TAGS.items()]}},
        )["Distribution"]
        print(f"• Distribution created: {dist['Id']} (first deployment takes a few minutes)")
    return dist


def delete_all(session, bucket: str) -> None:
    cf, s3 = session.client("cloudfront"), session.client("s3")
    existing = find_distribution(cf)
    if existing:
        current = cf.get_distribution_config(Id=existing["Id"])
        cfg = current["DistributionConfig"]
        if cfg["Enabled"]:
            cfg["Enabled"] = False
            cf.update_distribution(Id=existing["Id"], IfMatch=current["ETag"], DistributionConfig=cfg)
            print("• Disabling the distribution (CloudFront needs it disabled before deleting; a few minutes)...")
        cf.get_waiter("distribution_deployed").wait(Id=existing["Id"])
        cf.delete_distribution(Id=existing["Id"], IfMatch=cf.get_distribution_config(Id=existing["Id"])["ETag"])
        print(f"• Distribution deleted: {existing['Id']}")
    for item in cf.list_origin_access_controls()["OriginAccessControlList"].get("Items", []):
        if item["Name"] == OAC_NAME:
            cf.delete_origin_access_control(Id=item["Id"], IfMatch=cf.get_origin_access_control(Id=item["Id"])["ETag"])
            print(f"• Origin access control deleted: {OAC_NAME}")
    try:
        for page in s3.get_paginator("list_objects_v2").paginate(Bucket=bucket):
            objs = [{"Key": o["Key"]} for o in page.get("Contents", [])]
            if objs:
                s3.delete_objects(Bucket=bucket, Delete={"Objects": objs})
        s3.delete_bucket(Bucket=bucket)
        print(f"• Bucket deleted: s3://{bucket}")
    except s3.exceptions.NoSuchBucket:
        pass


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--profile", help="AWS profile; otherwise AWS_* variables, otherwise .env")
    ap.add_argument("--region", default=None, help="default: AWS_REGION, otherwise us-east-1")
    ap.add_argument("--api-url", help="API Gateway URL of box ②: routes /v1/* to it on the site's own URL")
    ap.add_argument("--dry-run", action="store_true", help="print what would be published and created, change nothing")
    ap.add_argument("--delete", action="store_true", help="delete the distribution, its access control and the bucket")
    args = ap.parse_args()

    import os

    import boto3

    if not args.profile:
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        from deploy_context_lambda import load_dotenv  # AWS_* from the git-ignored .env, never overrides

        load_dotenv()
    region = args.region or os.environ.get("AWS_REGION", "us-east-1")
    session = boto3.Session(profile_name=args.profile, region_name=region)
    account = session.client("sts").get_caller_identity()["Account"]
    bucket = f"alphaforge-web-{account}-{region}"
    print(f"• Account: {account}  region: {region}  bucket: {bucket}")

    if args.delete:
        delete_all(session, bucket)
        return
    if args.api_url:
        api_origin(args.api_url)  # fail fast on a bad URL
    cognito = FRONTEND / "config.js"
    config_text = config_js(cognito.read_text(encoding="utf-8") if cognito.is_file() else None)
    if not re.search(r'"auth":\s*"cognito"', config_text):
        print("! No Cognito settings in frontend/config.js: the deployed page would run in dev mode (no sign-in).")

    if args.dry_run:
        print("Dry run: nothing is created or changed.")
        for key, path in site_files():
            print(f"  would upload {key:28} {content_type(key):34} {cache_control(key)}")
        print(f"  would upload {'config.js':28} {content_type('config.js'):34} {cache_control('config.js')}"
              f"  (Cognito settings: {'yes' if cognito.is_file() else 'no'})")
        existing = find_distribution(session.client("cloudfront"))
        print(f"  would {'update distribution ' + existing['Id'] if existing else 'create a CloudFront distribution'}"
              f" ({COMMENT}), private bucket read through {OAC_NAME}")
        print(f"  /v1/* → {args.api_url}" if args.api_url else "  no /v1/* route (pass --api-url once the API exists)")
        return

    s3, cf = session.client("s3"), session.client("cloudfront")
    ensure_bucket(s3, bucket, region)
    upload(s3, bucket, config_text)
    dist = ensure_distribution(cf, bucket, region, args.api_url)
    s3.put_bucket_policy(Bucket=bucket, Policy=json.dumps(bucket_policy(bucket, dist["ARN"])))
    cf.create_invalidation(DistributionId=dist["Id"], InvalidationBatch={
        "Paths": {"Quantity": 1, "Items": ["/*"]}, "CallerReference": f"deploy-{int(time.time())}"})
    print(f"✓ Site: https://{dist['DomainName']}" + (f"  (API on /v1/* → {args.api_url})" if args.api_url else
                                                     "  (no API route yet: pass --api-url when the API is deployed)"))


if __name__ == "__main__":
    main()
